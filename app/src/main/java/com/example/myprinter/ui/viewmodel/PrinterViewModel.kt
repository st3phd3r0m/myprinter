package com.example.myprinter.ui.viewmodel

import android.app.Application
import android.hardware.usb.UsbDevice
import androidx.lifecycle.AndroidViewModel
import androidx.lifecycle.viewModelScope
import com.example.myprinter.R
import com.example.myprinter.usb.PrintOptions
import com.example.myprinter.usb.PrinterConnectionState
import com.example.myprinter.usb.UsbPrinterManager
import kotlinx.coroutines.delay
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.launch
import kotlinx.coroutines.withContext
import android.net.Uri

class PrinterViewModel(application: Application) : AndroidViewModel(application) {
    private val usbPrinterManager = UsbPrinterManager(application)
    
    val connectionState: StateFlow<PrinterConnectionState> = usbPrinterManager.connectionState
    val debugLogs: StateFlow<List<String>> = usbPrinterManager.debugLogs

    private val _discoveredPrinters = MutableStateFlow<List<UsbDevice>>(emptyList())
    val discoveredPrinters: StateFlow<List<UsbDevice>> = _discoveredPrinters.asStateFlow()

    private val _printerStatus = MutableStateFlow<String>("")
    val printerStatus: StateFlow<String> = _printerStatus.asStateFlow()

    private val _sendFileStatus = MutableStateFlow<String?>(null)
    val sendFileStatus: StateFlow<String?> = _sendFileStatus.asStateFlow()

    fun scanForPrinters() {
        _discoveredPrinters.value = usbPrinterManager.discoverPrinters()
    }

    fun connectToPrinter(device: UsbDevice) {
        usbPrinterManager.requestPermission(device)
    }

    fun refreshStatus() {
        viewModelScope.launch {
            _printerStatus.value = withContext(Dispatchers.IO) {
                usbPrinterManager.checkStatus()
            }
        }
    }

    suspend fun printDocument(uri: Uri, options: PrintOptions): Boolean {
        return withContext(Dispatchers.IO) {
            usbPrinterManager.printDocument(uri, options)
        }
    }

    // Send a ready-made printer file (e.g. a PCL stream generated by hpcups on a PC) over USB
    fun printRawFile(uri: Uri) {
        val app = getApplication<Application>()
        viewModelScope.launch {
            val result = withContext(Dispatchers.IO) {
                try {
                    val data = app.contentResolver.openInputStream(uri)?.use { it.readBytes() }
                        ?: return@withContext app.getString(R.string.raw_open_failed)
                    if (usbPrinterManager.printRaw(data)) {
                        app.getString(R.string.raw_sent, data.size)
                    } else {
                        app.getString(R.string.raw_send_failed)
                    }
                } catch (e: Exception) {
                    app.getString(R.string.raw_error, e.message)
                }
            }
            _sendFileStatus.value = result
            delay(4000)
            _sendFileStatus.value = null
        }
    }

    private val _exportStatus = MutableStateFlow<String?>(null)
    val exportStatus: StateFlow<String?> = _exportStatus.asStateFlow()

    fun clearLogs() {
        usbPrinterManager.clearLogs()
    }

    fun exportLogs() {
        _exportStatus.value = usbPrinterManager.exportLogsToDownloads()
        viewModelScope.launch {
            delay(3000)
            _exportStatus.value = null
        }
    }

    fun disconnect() {
        usbPrinterManager.disconnect()
        _printerStatus.value = ""
    }

    override fun onCleared() {
        super.onCleared()
        usbPrinterManager.cleanup()
    }
}
