@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun PrinterConnectionScreen(
    viewModel: PrinterViewModel,
    onBack: () -> Unit
) {
    val connectionState by viewModel.connectionState.collectAsState()
    val discoveredPrinters by viewModel.discoveredPrinters.collectAsState()
    val printerStatus by viewModel.printerStatus.collectAsState()
    val exportStatus by viewModel.exportStatus.collectAsState()
    val sendFileStatus by viewModel.sendFileStatus.collectAsState()
    val context = LocalContext.current

    LaunchedEffect(exportStatus) {
        exportStatus?.let {
            Toast.makeText(context, it, Toast.LENGTH_LONG).show()
        }
    }

    LaunchedEffect(sendFileStatus) {
        sendFileStatus?.let {
            Toast.makeText(context, it, Toast.LENGTH_LONG).show()
        }
    }

    // Pick a ready-made printer file (e.g. PCL generated by hpcups on a PC) and send it over USB
    val pickLauncher = rememberLauncherForActivityResult(
        contract = ActivityResultContracts.OpenDocument()
    ) { uri: Uri? ->
        uri?.let { viewModel.printRawFile(it) }
    }

    LaunchedEffect(Unit) {
        viewModel.scanForPrinters()
    }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text(stringResource(R.string.connect_title)) },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(Icons.AutoMirrored.Rounded.ArrowBack, contentDescription = stringResource(R.string.back))
                    }
                },
                actions = {
                    IconButton(onClick = { viewModel.scanForPrinters() }) {
                        Icon(Icons.Rounded.Refresh, contentDescription = stringResource(R.string.refresh))
                    }
                    // The log file is the only diagnostic available while the phone is on the printer.
                    IconButton(onClick = { viewModel.exportLogs() }) {
                        Icon(Icons.Rounded.Save, contentDescription = stringResource(R.string.logs_save))
                    }
                }
            )
        }
    ) { innerPadding ->
        Column(
            modifier = Modifier
                .padding(innerPadding)
                .fillMaxSize()
                .padding(16.dp)
        ) {
            ConnectionStatusCard(
                connectionState,
                printerStatus,
                onRefreshStatus = { viewModel.refreshStatus() },
                onSendPrinterFile = { pickLauncher.launch(arrayOf("*/*")) }
            )

            Spacer(modifier = Modifier.height(24.dp))
            
            Text(
                text = stringResource(R.string.printers_available),
                style = MaterialTheme.typography.titleMedium,
                fontWeight = FontWeight.Bold
            )
            
            Spacer(modifier = Modifier.height(8.dp))
            
            if (discoveredPrinters.isEmpty()) {
                Box(modifier = Modifier.weight(1f), contentAlignment = Alignment.Center) {
                    Text(stringResource(R.string.printers_none))
                }
            } else {
                LazyColumn(
                    modifier = Modifier.weight(1f),
                    verticalArrangement = Arrangement.spacedBy(8.dp)
                ) {
                    items(discoveredPrinters) { device ->
                        PrinterItem(device = device, onClick = { viewModel.connectToPrinter(device) })
                    }
                }
            }
        }
    }
}

@Composable
fun ConnectionStatusCard(
    state: PrinterConnectionState,
    status: String,
    onRefreshStatus: () -> Unit,
    onSendPrinterFile: () -> Unit
) {
    Card(
        modifier = Modifier.fillMaxWidth(),
        colors = CardDefaults.cardColors(
            containerColor = when (state) {
                is PrinterConnectionState.Connected -> MaterialTheme.colorScheme.primaryContainer
                is PrinterConnectionState.Error -> MaterialTheme.colorScheme.errorContainer
                else -> MaterialTheme.colorScheme.surfaceVariant
            }
        )
    ) {
        Column(
            modifier = Modifier.padding(16.dp)
        ) {
            Row(verticalAlignment = Alignment.CenterVertically) {
                Icon(
                    imageVector = when (state) {
                        is PrinterConnectionState.Connected -> Icons.Rounded.CheckCircle
                        is PrinterConnectionState.Error -> Icons.Rounded.Error
                        is PrinterConnectionState.RequestingPermission -> Icons.Rounded.Lock
                        else -> Icons.Rounded.Usb
                    },
                    contentDescription = null,
                    tint = when (state) {
                        is PrinterConnectionState.Connected -> MaterialTheme.colorScheme.primary
                        is PrinterConnectionState.Error -> MaterialTheme.colorScheme.error
                        else -> MaterialTheme.colorScheme.onSurfaceVariant
                    }
                )
                Spacer(modifier = Modifier.width(12.dp))
                Text(
                    text = when (state) {
                        is PrinterConnectionState.Idle -> stringResource(R.string.state_disconnected)
                        is PrinterConnectionState.RequestingPermission -> stringResource(R.string.state_requesting)
                        is PrinterConnectionState.Connected -> stringResource(R.string.state_connected, state.model)
                        is PrinterConnectionState.Error -> stringResource(R.string.state_error, state.message)
                        is PrinterConnectionState.Disconnected -> stringResource(R.string.state_disconnected)
                    },
                    style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.Bold
                )
            }
            
            if (state is PrinterConnectionState.Connected) {
                Spacer(modifier = Modifier.height(16.dp))
                HorizontalDivider()
                Spacer(modifier = Modifier.height(16.dp))
                Text(
                    text = stringResource(R.string.status_label),
                    style = MaterialTheme.typography.labelLarge,
                    color = MaterialTheme.colorScheme.primary
                )
                Text(
                    text = status.ifEmpty { stringResource(R.string.status_hint) },
                    style = MaterialTheme.typography.bodyMedium
                )
                Spacer(modifier = Modifier.height(8.dp))
                ElevatedButton(
                    onClick = onRefreshStatus,
                    modifier = Modifier.align(Alignment.End),
                    shape = MaterialTheme.shapes.medium
                ) {
                    Icon(Icons.Rounded.Refresh, contentDescription = null, modifier = Modifier.size(18.dp))
                    Spacer(modifier = Modifier.width(8.dp))
                    Text(stringResource(R.string.status_refresh))
                }
                Spacer(modifier = Modifier.height(8.dp))
                OutlinedButton(
                    onClick = onSendPrinterFile,
                    modifier = Modifier.align(Alignment.End),
                    shape = MaterialTheme.shapes.medium
                ) {
                    Text(stringResource(R.string.send_test_file))
                }
            }
        }
    }
}

@Composable
fun PrinterItem(device: UsbDevice, onClick: () -> Unit) {
    OutlinedCard(
        modifier = Modifier
            .fillMaxWidth()
            .clickable(onClick = onClick)
    ) {
        Row(
            modifier = Modifier
                .padding(16.dp)
                .fillMaxWidth(),
            verticalAlignment = Alignment.CenterVertically
        ) {
            Icon(Icons.Rounded.Print, contentDescription = null)
            Spacer(modifier = Modifier.width(16.dp))
            Column {
                Text(
                    text = device.productName ?: stringResource(R.string.printer_unknown),
                    style = MaterialTheme.typography.bodyLarge,
                    fontWeight = FontWeight.Bold
                )
                Text(
                    text = "VID: ${String.format("0x%04X", device.vendorId)} PID: ${String.format("0x%04X", device.productId)}",
                    style = MaterialTheme.typography.bodySmall
                )
            }
            Spacer(modifier = Modifier.weight(1f))
            Icon(Icons.Rounded.ChevronRight, contentDescription = null)
        }
    }
}
