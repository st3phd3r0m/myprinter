@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun PrinterConnectionScreen(
    viewModel: PrinterViewModel,
    onBack: () -> Unit
) {
    val connectionState by viewModel.connectionState.collectAsState()
    val discoveredPrinters by viewModel.discoveredPrinters.collectAsState()
    val printerStatus by viewModel.printerStatus.collectAsState()
    val debugLogs by viewModel.debugLogs.collectAsState()
    val exportStatus by viewModel.exportStatus.collectAsState()
    val sendFileStatus by viewModel.sendFileStatus.collectAsState()
    val context = LocalContext.current

    LaunchedEffect(exportStatus) {
        exportStatus?.let {
            Toast.makeText(context, it, Toast.LENGTH_LONG).show()
        }
    }

    LaunchedEffect(sendFileStatus) {
        sendFileStatus?.let {
            Toast.makeText(context, it, Toast.LENGTH_LONG).show()
        }
    }

    // Pick a ready-made printer file (e.g. PCL generated by hpcups on a PC) and send it over USB
    val pickLauncher = rememberLauncherForActivityResult(
        contract = ActivityResultContracts.OpenDocument()
    ) { uri: Uri? ->
        uri?.let { viewModel.printRawFile(it) }
    }

    LaunchedEffect(Unit) {
        viewModel.scanForPrinters()
    }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("Connect Printer") },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(Icons.AutoMirrored.Rounded.ArrowBack, contentDescription = "Back")
                    }
                },
                actions = {
                    IconButton(onClick = { viewModel.scanForPrinters() }) {
                        Icon(Icons.Rounded.Refresh, contentDescription = "Refresh")
                    }
                }
            )
        }
    ) { innerPadding ->
        Column(
            modifier = Modifier
                .padding(innerPadding)
                .fillMaxSize()
                .padding(16.dp)
        ) {
            ConnectionStatusCard(
                connectionState,
                printerStatus,
                onRefreshStatus = { viewModel.refreshStatus() },
                onSendPrinterFile = { pickLauncher.launch(arrayOf("*/*")) }
            )

            Spacer(modifier = Modifier.height(24.dp))
            
            Text(
                text = "Available Printers",
                style = MaterialTheme.typography.titleMedium,
                fontWeight = FontWeight.Bold
            )
            
            Spacer(modifier = Modifier.height(8.dp))
            
            if (discoveredPrinters.isEmpty()) {
                Box(modifier = Modifier.weight(1f), contentAlignment = Alignment.Center) {
                    Text("No printers found. Connect a USB printer.")
                }
            } else {
                LazyColumn(
                    modifier = Modifier.weight(1f),
                    verticalArrangement = Arrangement.spacedBy(8.dp)
                ) {
                    items(discoveredPrinters) { device ->
                        PrinterItem(device = device, onClick = { viewModel.connectToPrinter(device) })
                    }
                }
            }

            Spacer(modifier = Modifier.height(16.dp))

            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Text(
                    text = "System Logs",
                    style = MaterialTheme.typography.labelMedium,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
                Row {
                    TextButton(
                        onClick = { viewModel.clearLogs() },
                        contentPadding = PaddingValues(horizontal = 8.dp, vertical = 0.dp)
                    ) {
                        Icon(Icons.Rounded.DeleteSweep, contentDescription = null, modifier = Modifier.size(16.dp))
                        Spacer(modifier = Modifier.width(4.dp))
                        Text("Clear", fontSize = 12.sp)
                    }
                    TextButton(
                        onClick = { viewModel.exportLogs() },
                        contentPadding = PaddingValues(horizontal = 8.dp, vertical = 0.dp)
                    ) {
                        Icon(Icons.Rounded.Save, contentDescription = null, modifier = Modifier.size(16.dp))
                        Spacer(modifier = Modifier.width(4.dp))
                        Text("Save Logs", fontSize = 12.sp)
                    }
                }
            }
            Card(
                modifier = Modifier
                    .fillMaxWidth()
                    .height(120.dp),
                colors = CardDefaults.cardColors(containerColor = Color.Black),
                shape = MaterialTheme.shapes.small
            ) {
                LazyColumn(
                    modifier = Modifier.padding(8.dp),
                    reverseLayout = false
                ) {
                    items(debugLogs) { log ->
                        Text(
                            text = "> $log",
                            color = Color.Green,
                            fontFamily = FontFamily.Monospace,
                            fontSize = 10.sp
                        )
                    }
                }
            }
        }
    }
}

@Composable
fun ConnectionStatusCard(
    state: PrinterConnectionState,
    status: String,
    onRefreshStatus: () -> Unit,
    onSendPrinterFile: () -> Unit
) {
    Card(
        modifier = Modifier.fillMaxWidth(),
        colors = CardDefaults.cardColors(
            containerColor = when (state) {
                is PrinterConnectionState.Connected -> MaterialTheme.colorScheme.primaryContainer
                is PrinterConnectionState.Error -> MaterialTheme.colorScheme.errorContainer
                else -> MaterialTheme.colorScheme.surfaceVariant
            }
        )
    ) {
        Column(
            modifier = Modifier.padding(16.dp)
        ) {
            Row(verticalAlignment = Alignment.CenterVertically) {
                Icon(
                    imageVector = when (state) {
                        is PrinterConnectionState.Connected -> Icons.Rounded.CheckCircle
                        is PrinterConnectionState.Error -> Icons.Rounded.Error
                        is PrinterConnectionState.RequestingPermission -> Icons.Rounded.Lock
                        else -> Icons.Rounded.Usb
                    },
                    contentDescription = null,
                    tint = when (state) {
                        is PrinterConnectionState.Connected -> MaterialTheme.colorScheme.primary
                        is PrinterConnectionState.Error -> MaterialTheme.colorScheme.error
                        else -> MaterialTheme.colorScheme.onSurfaceVariant
                    }
                )
                Spacer(modifier = Modifier.width(12.dp))
                Text(
                    text = when (state) {
                        is PrinterConnectionState.Idle -> "Disconnected"
                        is PrinterConnectionState.RequestingPermission -> "Requesting Permission..."
                        is PrinterConnectionState.Connected -> "Connected: ${state.model}"
                        is PrinterConnectionState.Error -> "Error: ${state.message}"
                        is PrinterConnectionState.Disconnected -> "Disconnected"
                    },
                    style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.Bold
                )
            }
            
            if (state is PrinterConnectionState.Connected) {
                Spacer(modifier = Modifier.height(16.dp))
                HorizontalDivider()
                Spacer(modifier = Modifier.height(16.dp))
                Text(
                    text = "Printer Status:",
                    style = MaterialTheme.typography.labelLarge,
                    color = MaterialTheme.colorScheme.primary
                )
                Text(
                    text = status.ifEmpty { "Click refresh to check status" },
                    style = MaterialTheme.typography.bodyMedium
                )
                Spacer(modifier = Modifier.height(8.dp))
                ElevatedButton(
                    onClick = onRefreshStatus,
                    modifier = Modifier.align(Alignment.End),
                    shape = MaterialTheme.shapes.medium
                ) {
                    Icon(Icons.Rounded.Refresh, contentDescription = null, modifier = Modifier.size(18.dp))
                    Spacer(modifier = Modifier.width(8.dp))
                    Text("Refresh Status")
                }
                Spacer(modifier = Modifier.height(8.dp))
                OutlinedButton(
                    onClick = onSendPrinterFile,
                    modifier = Modifier.align(Alignment.End),
                    shape = MaterialTheme.shapes.medium
                ) {
                    Text("Envoyer un fichier d'impression (test)")
                }
            }
        }
    }
}

@Composable
fun PrinterItem(device: UsbDevice, onClick: () -> Unit) {
    OutlinedCard(
        modifier = Modifier
            .fillMaxWidth()
            .clickable(onClick = onClick)
    ) {
        Row(
            modifier = Modifier
                .padding(16.dp)
                .fillMaxWidth(),
            verticalAlignment = Alignment.CenterVertically
        ) {
            Icon(Icons.Rounded.Print, contentDescription = null)
            Spacer(modifier = Modifier.width(16.dp))
            Column {
                Text(
                    text = device.productName ?: "Unknown Printer",
                    style = MaterialTheme.typography.bodyLarge,
                    fontWeight = FontWeight.Bold
                )
                Text(
                    text = "VID: ${String.format("0x%04X", device.vendorId)} PID: ${String.format("0x%04X", device.productId)}",
                    style = MaterialTheme.typography.bodySmall
                )
            }
            Spacer(modifier = Modifier.weight(1f))
            Icon(Icons.Rounded.ChevronRight, contentDescription = null)
        }
    }
}
